#!/usr/bin/env python3
"""Export the string rows of the memory as i18n building blocks.

Two drafts are written, for the upstream i18n PRs:
  * a JavaScript dictionary part:  { key: { zh: ..., en: ... } }
  * an Android values-en/strings.xml draft:  <string name="key">en</string>

Only rows of kind "string" are exported. Keys are generated from the row's
context (the nearest function) and a per-context counter, so they are stable
and unique. This is a draft: a person renames the keys before merging.

Python 3 standard library only.
"""

import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import tm_common as tm  # noqa: E402


def make_keys(rows):
    """Assign a stable, unique key to each string row."""
    keys = []
    counter = {}
    for row in rows:
        base = re.sub(r"[^A-Za-z0-9]+", "_", row.get("context", "")).strip("_")
        if not base:
            base = "str"
        counter[base] = counter.get(base, 0) + 1
        keys.append("%s_%d" % (base, counter[base]))
    return keys


def js_escape(text):
    return text.replace("\\", "\\\\").replace("'", "\\'")


def xml_escape(text):
    out = (text.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("\"", "&quot;")
                .replace("'", "&apos;"))
    return out


def export_js(rows, keys, path):
    lines = [
        "// generated by export_i18n.py from s23-zh-en.tsv (draft)",
        "// rename the keys before merging.",
        "const S23_I18N = {",
    ]
    for key, row in zip(keys, rows):
        lines.append("  %s: { zh: '%s', en: '%s' }," % (
            key, js_escape(row["zh"]), js_escape(row["en"])))
    lines.append("};")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def export_android(rows, keys, path):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- generated by export_i18n.py from s23-zh-en.tsv (draft) -->",
        "<resources>",
    ]
    for key, row in zip(keys, rows):
        lines.append('  <string name="%s">%s</string>' % (
            key, xml_escape(row["en"])))
    lines.append("</resources>")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tm", default=None,
                    help="path to the TSV memory (default: s23-zh-en.tsv next to this script)")
    ap.add_argument("--out-js", default=None,
                    help="output JS dictionary path (default: <repo>/tools/i18n/s23-i18n.js)")
    ap.add_argument("--out-xml", default=None,
                    help="output Android strings.xml path (default: <repo>/tools/i18n/strings-en.xml)")
    ap.add_argument("--repo", default=os.getcwd(),
                    help="repo root used to default the output paths")
    args = ap.parse_args(argv)

    default_tm = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              "s23-zh-en.tsv")
    rows = [r for r in tm.read_tsv(args.tm or default_tm) if r["kind"] == "string"]
    keys = make_keys(rows)

    out_js = args.out_js or os.path.join(args.repo, "tools", "i18n", "s23-i18n.js")
    out_xml = args.out_xml or os.path.join(args.repo, "tools", "i18n", "strings-en.xml")
    os.makedirs(os.path.dirname(out_js) or ".", exist_ok=True)
    os.makedirs(os.path.dirname(out_xml) or ".", exist_ok=True)
    export_js(rows, keys, out_js)
    export_android(rows, keys, out_xml)

    print("string rows: %d" % len(rows))
    print("wrote %s" % out_js)
    print("wrote %s" % out_xml)
    return 0


if __name__ == "__main__":
    sys.exit(main())
